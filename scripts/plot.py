#!/usr/bin/env python3
"""Figures + results/summary.md from eval.csv, behavior.csv, training_curves.csv.   python3 scripts/plot.py"""
import pathlib
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from prl import plotstyle  # noqa: E402
from prl.plotstyle import MUTED, SERIES  # noqa: E402

plotstyle.apply()
import matplotlib.pyplot as plt  # noqa: E402

RES = pathlib.Path(__file__).resolve().parents[1] / "results"
ORDER = ["capture_point", "ppo_full", "ppo_residual", "sac_full", "sac_residual"]
COLOR = {"capture_point": "#1f1f1e", "ppo_full": SERIES[0], "ppo_residual": SERIES[2], "sac_full": SERIES[1],
         "sac_residual": SERIES[6]}
LABEL = {"capture_point": "capture-point controller (baseline)", "ppo_full": "PPO, full policy",
         "ppo_residual": "PPO, residual on capture point", "sac_full": "SAC, full policy",
         "sac_residual": "SAC, residual on capture point"}


def md(df, fmt=".3g"):
    cols = list(df.columns)
    out = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(f"{v:{fmt}}" if isinstance(v, (float, np.floating)) else str(v) for v in r) + " |")
    return "\n".join(out)


def curve(ax, df, title):
    for p in ORDER:
        d = df[df.policy == p]
        if d.empty:
            continue
        g = d.groupby("push").success
        m, lo, hi = g.mean(), g.min(), g.max()
        ax.plot(m.index, 100 * m.values, marker="o", ms=3, color=COLOR[p], label=LABEL[p],
                ls="--" if p == "capture_point" else "-")
        if d.seed.nunique() > 1:
            ax.fill_between(m.index, 100 * lo.values, 100 * hi.values, color=COLOR[p], alpha=0.12, lw=0)
    ax.axvline(1.4, color=MUTED, ls=":", lw=1)
    ax.text(1.42, 96, "training range ends", fontsize=7, color=MUTED, va="top")
    ax.set_xlabel("push magnitude [m/s]")
    ax.set_ylabel("recovered [%]")
    ax.set_ylim(-3, 103)
    ax.set_title(title)


def main():
    ev = pd.read_csv(RES / "eval.csv")
    parts = ["# Results (generated by scripts/plot.py)"]
    fig, axes = plt.subplots(1, 2, figsize=(10.5, 3.9), sharey=True)
    curve(axes[0], ev[ev.dist == "train_dist"], "Training dynamics (omega +/-5 %, 1.5 cm foot noise)")
    curve(axes[1], ev[ev.dist == "ood_omega10_foot3cm"], "Shifted: omega +/-10 %, 3 cm foot noise")
    axes[0].legend(fontsize=7, loc="lower left")
    fig.tight_layout()
    fig.savefig(RES / "fig_success_vs_push.png")
    plt.close(fig)

    rows = []
    for p in ORDER:
        for dist in ["train_dist", "ood_omega10_foot3cm"]:
            d = ev[(ev.policy == p) & (ev.dist == dist)]
            if d.empty:
                continue
            per_seed = d[d.push <= 1.4].groupby("seed").success.mean()
            rows.append({"policy": p, "dynamics": dist, "seeds": len(per_seed),
                         "mean success 0-1.4 m/s [%]": 100 * per_seed.mean(),
                         "seed range [%]": f"{100 * per_seed.min():.1f}-{100 * per_seed.max():.1f}",
                         "at 1.0 m/s [%]": 100 * d[d.push == 1.0].success.mean(),
                         "at 1.4 m/s [%]": 100 * d[d.push == 1.4].success.mean(),
                         "at 1.8 m/s [%]": 100 * d[d.push == 1.8].success.mean()})
    parts.append("## Recovery rate (2000 episodes per push level and seed)\n\n" + md(pd.DataFrame(rows)))

    tc = pd.read_csv(RES / "training_curves.csv")
    fig, ax = plt.subplots(figsize=(6.6, 3.4))
    for algo in ["ppo_full", "ppo_residual", "sac_full", "sac_residual"]:
        d = tc[tc.algo == algo]
        if d.empty:
            continue
        g = d.groupby("env_steps").train_success.mean().rolling(5, min_periods=1).mean()
        ax.plot(g.index / 1e6, 100 * g.values, color=COLOR[algo], label=LABEL[algo])
    ax.set_xscale("log")
    ax.set_xlabel("environment steps (footsteps) [millions], log scale")
    ax.set_ylabel("training success [%] (with exploration)")
    ax.set_title("Learning curves, mean of 3 seeds")
    ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(RES / "fig_training.png")
    plt.close(fig)
    wall = tc.groupby(["algo", "seed"]).wall_s.max().groupby("algo").mean()
    steps = tc.groupby(["algo", "seed"]).env_steps.max().groupby("algo").mean()
    parts.append("## Training cost (mean per seed)\n\n" + md(pd.DataFrame({"algo": wall.index, "env steps": steps.values,
                                                                          "wall [s]": wall.values})))

    be = pd.read_csv(RES / "behavior.csv")
    fig, axes = plt.subplots(1, 2, figsize=(10.0, 3.4))
    for p in ORDER:
        d = be[be.policy == p].groupby("push").mean(numeric_only=True)
        if d.empty:
            continue
        axes[0].plot(d.index, d.T_first_step, marker="o", ms=3, color=COLOR[p], label=LABEL[p],
                     ls="--" if p == "capture_point" else "-")
        axes[1].plot(d.index, 100 * d.cop_first_step, marker="o", ms=3, color=COLOR[p], ls="--" if p == "capture_point" else "-")
    axes[0].set_xlabel("push magnitude [m/s]")
    axes[0].set_ylabel("first step duration [s]")
    axes[0].set_title("Step timing chosen after the push")
    axes[0].legend(fontsize=7)
    axes[1].set_xlabel("push magnitude [m/s]")
    axes[1].set_ylabel("|CoP x offset| in first step [cm]")
    axes[1].set_title("Ankle (CoP) use in the first step")
    fig.tight_layout()
    fig.savefig(RES / "fig_behavior.png")
    plt.close(fig)
    (RES / "summary.md").write_text("\n\n".join(parts) + "\n")
    print((RES / "summary.md").read_text())


if __name__ == "__main__":
    main()
